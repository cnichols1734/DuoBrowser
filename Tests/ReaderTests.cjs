const assert = require('node:assert/strict');
module.exports = async (page, source) => {
    let passed = 0;
    const check = (value) => { assert.ok(value); passed++; };
    const paragraph = 'A calm reading experience keeps the original article intact and never reads form values. '.repeat(5);
    await page.setContent(`<title>Reading fixture</title><article><h1>Heading</h1><p>${paragraph}<span style="display:none">CSS HIDDEN SECRET</span><span style="visibility:hidden">INVISIBLE SECRET</span></p><p>${paragraph}</p><form><input value="SECRET"><p>PRIVATE FORM</p></form><nav><p>Navigation</p></nav><p hidden>Hidden</p><p><textarea>NESTED SECRET</textarea></p><p>Text <span contenteditable>EDITABLE SECRET</span></p><p><script>window.nestedSecret=42</script></p><div contenteditable><p>UNSENT</p></div></article>`);
    const before = await page.content();
    const article = await page.evaluate(source);
    check(article.blocks.length === 3);
    check(article.blocks[0].kind === 'heading');
    check(!JSON.stringify(article).includes('SECRET'));
    check(!JSON.stringify(article).includes('CSS HIDDEN'));
    check(!JSON.stringify(article).includes('INVISIBLE'));
    check(!JSON.stringify(article).includes('PRIVATE FORM'));
    check(!JSON.stringify(article).includes('UNSENT'));
    check(!JSON.stringify(article).includes('Navigation'));
    check(!JSON.stringify(article).includes('Hidden'));
    check(!JSON.stringify(article).includes('NESTED SECRET'));
    check(!JSON.stringify(article).includes('EDITABLE SECRET'));
    check(!JSON.stringify(article).includes('nestedSecret'));
    check(await page.content() === before);
    await page.setContent('<div><p>Not an article</p></div>');
    check(await page.evaluate(source) === null);
    await page.setContent('<article><p>Too short</p></article>');
    check(await page.evaluate(source) === null);
    await page.setContent(`<article>${Array.from({length: 400}, () => `<p>${paragraph}</p>`).join('')}</article>`);
    const bounded = await page.evaluate(source);
    check(bounded.blocks.length <= 300);
    check(bounded.blocks.reduce((n,b) => n + b.text.length, 0) <= 108000);
    await page.setContent(`<article><blockquote><p>${paragraph}</p></blockquote><p>${paragraph}</p></article>`);
    check((await page.evaluate(source)).blocks.length === 2);
    await page.route('https://reader.example/**', route => route.abort());
    const image = '<img src="https://reader.example/photo.png" width="320" height="180" alt="A mountain & lake">';
    await page.setContent(`<article><p>${paragraph}</p><figure>${image}<figcaption>Mountain caption</figcaption></figure><p>${paragraph}</p></article>`);
    const illustrated = await page.evaluate(source);
    check(illustrated.blocks.map(block => block.kind).join(',') === 'paragraph,image,caption,paragraph');
    check(illustrated.blocks[1].url === 'https://reader.example/photo.png');
    check(illustrated.blocks[1].alt === 'A mountain & lake');
    check(illustrated.blocks[2].text === 'Mountain caption');
    await page.setContent(`<article><p>Before photo ${image} After photo</p><p>${paragraph}</p></article>`);
    const inline = await page.evaluate(source);
    check(inline.blocks.map(block => block.kind).join(',') === 'paragraph,image,paragraph,paragraph');
    check(inline.blocks[0].text === 'Before photo' && inline.blocks[2].text === 'After photo');
    await page.setContent(`<article><p>${paragraph}</p><img src="javascript:alert(1)" width="320" height="180"><img src="data:image/png,abc" width="320" height="180"><img src="https://user:secret@reader.example/photo.png" width="320" height="180"><img width="320" height="180"><p>${paragraph}</p></article>`);
    check((await page.evaluate(source)).blocks.every(block => block.kind !== 'image'));
    await page.setContent(`<article><p>${paragraph}</p><div hidden>${image}</div><img src="https://reader.example/pixel.png" width="1" height="1"><p>${paragraph}</p></article>`);
    check((await page.evaluate(source)).blocks.every(block => block.kind !== 'image'));
    await page.setContent(`<article><p>${paragraph}</p>${image.repeat(60)}<p>${paragraph}</p></article>`);
    check((await page.evaluate(source)).blocks.filter(block => block.kind === 'image').length === 40);
    await page.setContent(`<form><article><p>${paragraph}</p><p>${paragraph}</p></article></form>`);
    check(await page.evaluate(source) === null);
    await page.setContent(`<div style="display:none"><article><p>${paragraph}</p><p>${paragraph}</p></article></div>`);
    check(await page.evaluate(source) === null);
    await page.setContent(`<div aria-hidden="true"><article><p>${paragraph}</p><p>${paragraph}</p></article></div>`);
    check(await page.evaluate(source) === null);
    await page.setContent(`<article><p>${paragraph}</p><figure>${image}<figcaption><p>A nested caption</p></figcaption></figure><p>${paragraph}</p></article>`);
    const nestedCaption = await page.evaluate(source);
    check(nestedCaption.blocks.filter(block => block.kind === 'caption').length === 1);
    check(nestedCaption.blocks.find(block => block.kind === 'caption').text === 'A nested caption');
    await page.setContent(`<title>Search engine title — Publisher</title><article><header><h1>Visible article headline</h1><p>By a reporter</p>${image}</header><p>${paragraph}</p></article>`);
    const headerArticle = await page.evaluate(source);
    check(headerArticle.title === 'Visible article headline');
    check(headerArticle.blocks.map(block => block.kind).join(',') === 'heading,paragraph,image,paragraph');
    check(headerArticle.blocks[1].text === 'By a reporter');
    await page.setContent(`<main><header><h1>Site headline</h1>${image}</header><p>${paragraph}</p><p>${paragraph}</p></main>`);
    const mainArticle = await page.evaluate(source);
    check(mainArticle.blocks.every(block => block.kind === 'paragraph'));
    await page.setContent(`<header><article><h1>Global header headline</h1><p>${paragraph}</p><p>${paragraph}</p></article></header>`);
    check(await page.evaluate(source) === null);
    await page.setContent(`<title>Safe title</title><article><h1 hidden>Hidden headline</h1><p>${paragraph}</p><p>${paragraph}</p></article>`);
    check((await page.evaluate(source)).title === 'Safe title');
    await page.setContent(`<article><p>${paragraph}</p><figure><img role="presentation" src="https://reader.example/photo.png" width="640" height="360"><figcaption>An editorial photograph</figcaption></figure><p>${paragraph}</p></article>`);
    const presentationalPhoto = await page.evaluate(source);
    check(presentationalPhoto.blocks.map(block => block.kind).join(',') === 'paragraph,image,caption,paragraph');
    check(presentationalPhoto.blocks[1].url === 'https://reader.example/photo.png');
    await page.setContent(`<article><p>${paragraph}</p><ul><li>Important introduction<p>Nested detail paragraph.</p>Important trailing text.</li></ul><p>${paragraph}</p></article>`);
    const mixedList = await page.evaluate(source);
    check(mixedList.blocks.slice(1, -1).map(block => block.text).join('|') === 'Important introduction|Nested detail paragraph.|Important trailing text.');
    check(mixedList.blocks.filter(block => block.text === 'Nested detail paragraph.').length === 1);
    await page.setContent(`<article><p>${paragraph}</p><ul><li>Safe introduction<p>Safe nested detail.</p><form><input value="FORM SECRET"><p>FORM SECRET</p></form><span hidden>HIDDEN SECRET</span>Safe ending.</li></ul><p>${paragraph}</p></article>`);
    const mixedPrivate = await page.evaluate(source);
    check(mixedPrivate.blocks.slice(1, -1).map(block => block.text).join('|') === 'Safe introduction|Safe nested detail.|Safe ending.');
    check(!JSON.stringify(mixedPrivate).includes('SECRET'));
    await page.unroute('https://reader.example/**');
    return {passed};
};
